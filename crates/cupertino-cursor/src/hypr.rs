//! hyprcursor source theme writer (optional).
//!
//! Layout (see the hyprcursor documentation for theme authors): `manifest.hl` and a
//! `hyprcursors/<shape>/` directory per cursor with `meta.hl` and one PNG per size (animation
//! frames are consecutive `define_size` lines of the same size with a timeout). Images must be
//! square, so every frame is padded to a square canvas (content at the top-left) and the hotspot is
//! normalised by the side. `define_size` is the pixel side of the image — the declared size
//! equals the real size, so a consumer asking for a different size scales or picks the closest.
//! The output is a *source* theme: compile it with `hyprcursor-util --create`.

use crate::theme::{BuildOptions, Cursor};
use std::path::PathBuf;
use tiny_skia::{Pixmap, PixmapPaint, Transform};

fn square(img: &Pixmap) -> Pixmap {
    let side = img.width().max(img.height());
    let mut out = Pixmap::new(side, side).expect("non-empty canvas");
    out.draw_pixmap(
        0,
        0,
        img.as_ref(),
        &PixmapPaint::default(),
        Transform::identity(),
        None,
    );
    out
}

pub fn meta_hl(c: &Cursor) -> String {
    let first = &c.sizes[0].frames[0];
    let side = first.image.width().max(first.image.height()) as f64;
    let mut s = String::from("resize_algorithm = bilinear\n");
    s.push_str(&format!(
        "hotspot_x = {:.4}\nhotspot_y = {:.4}\n\n",
        (first.hotspot.0 as f64 + 0.5) / side,
        (first.hotspot.1 as f64 + 0.5) / side
    ));
    s.push_str(&format!("define_override = {}\n", c.name));
    for a in &c.aliases {
        s.push_str(&format!("define_override = {a}\n"));
    }
    s.push('\n');
    for v in &c.sizes {
        for (i, f) in v.frames.iter().enumerate() {
            let side = f.image.width().max(f.image.height());
            let file = file_name(side, i, v.frames.len());
            if v.frames.len() > 1 {
                s.push_str(&format!(
                    "define_size = {side}, {file}, {}\n",
                    f.delay_ms.max(1)
                ));
            } else {
                s.push_str(&format!("define_size = {side}, {file}\n"));
            }
        }
    }
    s
}

fn file_name(side: u32, frame: usize, frames: usize) -> String {
    if frames > 1 {
        format!("anim{side}_{frame}.png")
    } else {
        format!("image{side}.png")
    }
}

/// Write `<output>/<name>-hyprcursor/`; returns the directory.
pub fn write(o: &BuildOptions, cursors: &[Cursor], notice: &str) -> Result<PathBuf, String> {
    let dir = o.output.join(format!("{}-hyprcursor", o.name));
    if dir.exists() {
        if dir.join(crate::theme::MARKER_FILE).is_file() {
            std::fs::remove_dir_all(&dir).map_err(|e| e.to_string())?;
        } else if std::fs::read_dir(&dir)
            .map_err(|e| e.to_string())?
            .next()
            .is_some()
        {
            return Err(format!(
                "{} exists and was not generated by cupertino-cursor; refusing to overwrite it",
                dir.display()
            ));
        }
    }
    let shapes = dir.join("hyprcursors");
    std::fs::create_dir_all(&shapes).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("manifest.hl"), format!("name = {}\ndescription = Cursor theme generated by cupertino-cursor\nversion = 0.1\ncursors_directory = hyprcursors\n", o.name)).map_err(|e| e.to_string())?;
    std::fs::write(dir.join("README.txt"), notice).map_err(|e| e.to_string())?;
    for c in cursors {
        let shape = shapes.join(&c.name);
        std::fs::create_dir_all(&shape).map_err(|e| e.to_string())?;
        std::fs::write(shape.join("meta.hl"), meta_hl(c)).map_err(|e| e.to_string())?;
        for v in &c.sizes {
            for (i, f) in v.frames.iter().enumerate() {
                let sq = square(&f.image);
                sq.save_png(shape.join(file_name(sq.width(), i, v.frames.len())))
                    .map_err(|e| e.to_string())?;
            }
        }
    }
    std::fs::write(dir.join(crate::theme::MARKER_FILE), "").map_err(|e| e.to_string())?;
    Ok(dir)
}
