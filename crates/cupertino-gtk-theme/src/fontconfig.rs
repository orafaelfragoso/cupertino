//! Fontconfig snippet that maps the system UI font to the open substitute family.
//!
//! Rules: the generic `system-ui` and `ui-sans-serif` families resolve to the substitute, and so
//! does the default UI family of the common toolkits' stock themes (`Cantarell`, `Adwaita Sans`) —
//! each as a `binding="same" alias so an explicit user preference still wins. Optionally the
//! generic `sans-serif` family prefers the substitute too ([`FontOptions::map_sans_serif`], off by
//! default because it changes every application that asks for a generic sans). Rendering: grayscale
//! anti-aliasing and slight hinting (approximate; the design renders grayscale).

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FontOptions {
    pub family: String,
    pub map_sans_serif: bool,
    pub rendering: bool,
}

impl FontOptions {
    pub fn new(family: &str) -> Self {
        Self { family: family.into(), map_sans_serif: false, rendering: true }
    }
}

const SOURCES: [&str; 4] = ["system-ui", "ui-sans-serif", "Cantarell", "Adwaita Sans"];

pub fn snippet(o: &FontOptions) -> String {
    let mut s = String::new();
    s.push_str("<?xml version=\"1.0\"?>\n<!DOCTYPE fontconfig SYSTEM \"urn:fontconfig:fonts.dtd\">\n<fontconfig>\n");
    s.push_str("  <!-- Generated by cupertino-gtk-theme: maps the system UI font to the substitute family. -->\n");
    for src in SOURCES {
        s.push_str(&format!("  <alias binding=\"same\">\n    <family>{src}</family>\n    <prefer><family>{}</family></prefer>\n  </alias>\n", o.family));
    }
    if o.map_sans_serif {
        s.push_str(&format!("  <alias>\n    <family>sans-serif</family>\n    <prefer><family>{}</family></prefer>\n  </alias>\n", o.family));
    }
    if o.rendering {
        s.push_str("  <match target=\"font\">\n    <edit name=\"antialias\" mode=\"assign\"><bool>true</bool></edit>\n    <edit name=\"hinting\" mode=\"assign\"><bool>true</bool></edit>\n    <edit name=\"hintstyle\" mode=\"assign\"><const>hintslight</const></edit>\n    <edit name=\"rgba\" mode=\"assign\"><const>none</const></edit>\n  </match>\n");
    }
    s.push_str("</fontconfig>\n");
    s
}

/// Families named in `prefer` lists and aliases of a generated snippet (test helper).
pub fn alias_sources(xml: &str) -> Vec<String> {
    let mut v = Vec::new();
    let mut rest = xml;
    while let Some(i) = rest.find("<alias") {
        rest = &rest[i..];
        if let Some(f) = rest.find("<family>") {
            let after = &rest[f + 8..];
            if let Some(e) = after.find("</family>") {
                v.push(after[..e].to_string());
            }
        }
        rest = &rest[6..];
    }
    v
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_ui_families_to_the_substitute() {
        let x = snippet(&FontOptions::new("Inter"));
        assert!(x.contains("<prefer><family>Inter</family></prefer>"));
        let src = alias_sources(&x);
        for s in ["system-ui", "ui-sans-serif", "Cantarell", "Adwaita Sans"] {
            assert!(src.iter().any(|a| a == s), "{s} in {src:?}");
        }
        assert!(!src.iter().any(|a| a == "sans-serif"), "generic sans is untouched by default");
        assert!(x.contains("hintslight") && x.contains("<const>none</const>"));
    }

    #[test]
    fn options_toggle_sections() {
        let x = snippet(&FontOptions { family: "Inter".into(), map_sans_serif: true, rendering: false });
        assert!(alias_sources(&x).contains(&"sans-serif".to_string()));
        assert!(!x.contains("hintstyle"));
    }

    #[test]
    fn xml_is_balanced() {
        let x = snippet(&FontOptions::new("Inter"));
        for tag in ["alias", "prefer", "match", "fontconfig", "edit"] {
            assert_eq!(x.matches(&format!("<{tag}")).count(), x.matches(&format!("</{tag}>")).count(), "{tag}");
        }
    }
}
